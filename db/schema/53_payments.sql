-- Creates a pending order from an active online offer. The price comes from the
-- offer row, never from the client. Errors: OFFER_NOT_FOUND.
CREATE OR REPLACE FUNCTION public.order_create(
  p_user_id UUID,
  p_case_id TEXT,
  p_sku TEXT
)
RETURNS public.orders
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_offer case_offers%ROWTYPE;
  v_order orders%ROWTYPE;
BEGIN
  SELECT * INTO v_offer FROM case_offers
  WHERE case_id = p_case_id AND sku = p_sku AND kind = 'online' AND active;

  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'OFFER_NOT_FOUND';
  END IF;

  INSERT INTO orders (user_id, case_id, sku, amount_vnd, group_credits)
  VALUES (p_user_id, p_case_id, p_sku, v_offer.price_vnd, v_offer.group_credits)
  RETURNING * INTO v_order;

  RETURN v_order;
END;
$$;

-- Marks an order paid and grants (or extends) the license, in one transaction.
-- Locks the order row, so concurrent webhook deliveries cannot both grant.
-- Returns 'granted', 'already_paid' or 'amount_mismatch' (order marked 'failed').
-- Raises ORDER_NOT_FOUND.
CREATE OR REPLACE FUNCTION public.grant_license_for_order(
  p_order_code BIGINT,
  p_amount INTEGER,
  p_payload JSONB
)
RETURNS TEXT
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_order orders%ROWTYPE;
BEGIN
  SELECT * INTO v_order FROM orders WHERE order_code = p_order_code FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'ORDER_NOT_FOUND';
  END IF;

  IF v_order.status = 'paid' THEN
    RETURN 'already_paid';
  END IF;

  -- Returned, not raised: a raise would roll back the 'failed' mark.
  IF p_amount IS DISTINCT FROM v_order.amount_vnd THEN
    UPDATE orders
    SET status = 'failed', provider_payload = p_payload, updated_at = NOW()
    WHERE id = v_order.id;
    RETURN 'amount_mismatch';
  END IF;

  UPDATE orders
  SET status = 'paid', paid_at = NOW(), provider_payload = p_payload, updated_at = NOW()
  WHERE id = v_order.id;

  INSERT INTO licenses (user_id, case_id, group_credits, online_at)
  VALUES (v_order.user_id, v_order.case_id, v_order.group_credits, NOW())
  ON CONFLICT (user_id, case_id) DO UPDATE
  SET group_credits = licenses.group_credits + EXCLUDED.group_credits,
      online_at = COALESCE(licenses.online_at, NOW()),
      updated_at = NOW();

  RETURN 'granted';
END;
$$;

-- Redeems a box code for a user. Locks the code row.
-- Returns jsonb { case_id, result: 'activated' | 'already_yours' }.
-- Raises BOX_CODE_INVALID (unknown hash) or BOX_CODE_USED (other account).
CREATE OR REPLACE FUNCTION public.redeem_box_code(
  p_user_id UUID,
  p_code_hash TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_code box_codes%ROWTYPE;
BEGIN
  SELECT * INTO v_code FROM box_codes WHERE code_hash = p_code_hash FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'BOX_CODE_INVALID';
  END IF;

  IF v_code.redeemed_by IS NOT NULL THEN
    IF v_code.redeemed_by = p_user_id THEN
      RETURN jsonb_build_object('case_id', v_code.case_id, 'result', 'already_yours');
    END IF;
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'BOX_CODE_USED';
  END IF;

  UPDATE box_codes SET redeemed_by = p_user_id, redeemed_at = NOW()
  WHERE code_hash = p_code_hash;

  INSERT INTO licenses (user_id, case_id, box_activated_at)
  VALUES (p_user_id, v_code.case_id, NOW())
  ON CONFLICT (user_id, case_id) DO UPDATE
  SET box_activated_at = COALESCE(licenses.box_activated_at, NOW()),
      updated_at = NOW();

  RETURN jsonb_build_object('case_id', v_code.case_id, 'result', 'activated');
END;
$$;

-- Takes one online group credit before a room is created.
-- Returns the credits left, or -1 when there is none to take.
CREATE OR REPLACE FUNCTION public.license_use_group_credit(
  p_user_id UUID,
  p_case_id TEXT
)
RETURNS INTEGER
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_left INTEGER;
BEGIN
  UPDATE licenses
  SET group_credits = group_credits - 1, updated_at = NOW()
  WHERE user_id = p_user_id AND case_id = p_case_id AND group_credits > 0
  RETURNING group_credits INTO v_left;

  RETURN COALESCE(v_left, -1);
END;
$$;

-- Gives the credit back when room creation fails after license_use_group_credit.
CREATE OR REPLACE FUNCTION public.license_refund_group_credit(
  p_user_id UUID,
  p_case_id TEXT
)
RETURNS VOID
LANGUAGE sql
SET search_path = public
AS $$
  UPDATE licenses
  SET group_credits = group_credits + 1, updated_at = NOW()
  WHERE user_id = p_user_id AND case_id = p_case_id;
$$;

